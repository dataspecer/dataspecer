const english: SvgDiagramTexts = {
  profileOf: "profile of",
  mandatory: "<<mandatory>>", recommended: "<<recommended>>", optional: "<<optional>>",
  undefinedLevel: "<<undefined>>", represents: "Represents",
};

export type RenderOptions = ReturnType<typeof resolveOptions>;

/** Applies defaults and validates dimensions before any rendering begins. */
export function resolveOptions(options: SvgRenderOptions) {
  const fontSize = options.fontSize ?? 16;
  const padding = options.padding ?? 20;
  if (!Number.isFinite(fontSize) || fontSize <= 0 || !Number.isFinite(padding) || padding < 0) {
    throw new Error("SVG fontSize must be positive and padding non-negative; both must be finite.");
  }
  const dark = options.theme === "dark";
  const language = options.language ?? "en";
  return {
    ...options, fontSize, padding, language,
    background: options.background ?? (dark ? "#111827" : "#ffffff"),
    labelMode: options.labelMode ?? "entity",
    colorMode: options.colorMode ?? "entity",
    profileOfMode: options.profileOfMode ?? "label",
    showIris: options.showIris ?? true,
    showRangeDetails: options.showRangeDetails ?? true,
    showCardinalities: options.showCardinalities ?? true,
    linkTarget: options.linkTarget ?? "_self",
    onWarning: options.onWarning ?? ((message: string) => console.warn(message)),
    prefixes: { ...prefixes, ...options.prefixes },
    texts: {
      ...english,
      ...(language.split("-")[0] === "cs" ? {
        profileOf: "profiluje",
        mandatory: "<<povinné>>", recommended: "<<doporučené>>", optional: "<<volitelné>>",
        represents: "Reprezentuje",
      } : {}),
      ...options.texts,
    },
    palette: {
      body: dark ? "#1f2937" : "#ffffff",
      text: dark ? "#f9fafb" : "#000000",
      muted: dark ? "#9ca3af" : "#6b7280",
      border: dark ? "#d1d5db" : "#000000",
    },
  };
}
