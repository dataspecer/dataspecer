import type { EntityIdentifier } from "@dataspecer/core/entity-model";
import type { ModelIdentifier } from "@dataspecer/core/model";

/** Identifies one independently clickable part of a diagram. */
export interface SvgLinkContext {
  /** Profiles use the same kind as the entity they specialize. */
  kind: "class" | "attribute" | "relationship" | "generalization" | "profile-link" | "diagram";
  /** Owning semantic model, or the represented model for a diagram node. */
  modelId: ModelIdentifier;
  /** Null for diagram references, which represent a model. */
  entityId: EntityIdentifier | null;
  /** The containing visual node for attributes; otherwise the visual element. */
  visualEntityId: EntityIdentifier;
}

/** Localizable annotations generated by the renderer. */
export interface SvgDiagramTexts {
  /** Prefix for the list of immediately profiled entities. */
  profileOf: string;
  /** Mandatory requirement-level heading. */
  mandatory: string;
  /** Recommended requirement-level heading. */
  recommended: string;
  /** Optional requirement-level heading. */
  optional: string;
  /** Heading when ordered attributes return to an unspecified requirement level. */
  undefinedLevel: string;
  /** Prefix for the model represented by a diagram-reference node. */
  represents: string;
}

/** Presentation options; all dimensions are in SVG user units. */
export interface SvgRenderOptions {
  /** Default: light. Explicit model colors are preserved in either theme. */
  theme?: "light" | "dark";
  /** A CSS color or "transparent". Omit to use the theme background. */
  background?: string;
  /** Outer canvas padding. Default: 20. */
  padding?: number;
  /** System sans-serif font size. Default: 16. */
  fontSize?: number;
  /** Preferred label language. Default: en. */
  language?: string;
  /** Namespace IRI to prefix. Supplied entries override the built-in prefixes. */
  prefixes?: Record<string, string>;
  /** Source of displayed names. Default: entity. */
  labelMode?: "entity" | "iri" | "vocabulary";
  /** Source model for header and edge colors. Default: entity. */
  colorMode?: "entity" | "vocabulary";
  /** Display of immediate profile targets. Default: label. */
  profileOfMode?: "label" | "iri" | "hidden";
  /** Include class IRI rows unless the title already shows the IRI. Default: true. */
  showIris?: boolean;
  /** Include attribute range labels and cardinalities. Default: true. */
  showRangeDetails?: boolean;
  /** Include attribute and relationship cardinalities. Default: true. */
  showCardinalities?: boolean;
  /** Override generated diagram annotations. */
  texts?: Partial<SvgDiagramTexts>;
  /** Called once per rendered element. Null leaves that element unlinked. */
  getLink?: (context: SvgLinkContext) => string | null;
  /** Browsing context for links. Default: _self. */
  linkTarget?: "_self" | "_blank";
  /** Receives unresolved references, unsupported elements, and rejected links. */
  onWarning?: (message: string) => void;
}

